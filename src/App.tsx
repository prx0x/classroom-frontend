const customTitleHandler = ({
  resource,
  action,
  pathname,
}: {
  resource?: { meta?: { label?: string }; name?: string };
  action?: string;
  pathname?: string;
  autoGeneratedTitle: string;
}) => {
  if (pathname?.startsWith("/portal")) {
    const resourceName = resource?.meta?.label || resource?.name;
    if (resourceName) {
      const actionSuffix =
        action && action !== "list"
          ? ` | ${action.charAt(0).toUpperCase() + action.slice(1)}`
          : "";
      return `${resourceName}${actionSuffix} | IIIT Kota Classroom Portal`;
    }
    return "Classroom Portal | IIIT Kota";
  }

  const publicTitles: Record<string, string> = {
    "/": "Home | IIIT Kota",
    "/login": "Sign In | IIIT Kota Classroom Portal",
    "/about": "About | IIIT Kota",
    "/academics": "Academics | IIIT Kota",
    "/campus": "Campus | IIIT Kota",
    "/student-life": "Student Life | IIIT Kota",
    "/admissions": "Admissions | IIIT Kota",
    "/contact": "Contact | IIIT Kota",
  };

  return (
    publicTitles[pathname || ""] ||
    "Indian Institute of Information Technology, Kota | IIIT Kota"
  );
};

